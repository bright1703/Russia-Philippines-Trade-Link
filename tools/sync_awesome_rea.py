"""Sync the Awesome-REA knowledge base into knowledge/awesome-rea/.

Awesome Reverse Engineering Anything (https://awesomerea.org/,
https://github.com/reacher-z/Awesome-REA) publishes its curated catalog for
machines through llms.txt and a static JSON API (api/v1). This script reads
both, verifies every API file against the SHA-256 published in
api/v1/index.json and writes compact local copies:

    knowledge/awesome-rea/llms.txt         verbatim navigation file
    knowledge/awesome-rea/categories.json  verbatim categories endpoint
    knowledge/awesome-rea/resources.json   compact curated resources
    knowledge/awesome-rea/papers.json      compact research bibliography
    knowledge/awesome-rea/INDEX.md         resources grouped by category
    knowledge/awesome-rea/source.json      versions, counts and checksums

Run from the repository root:

    python3 tools/sync_awesome_rea.py

The site chat (data/chat-knowledge.json) is not touched.
"""
import collections, datetime, hashlib, json, os, urllib.request

SITE = "https://awesomerea.org"
API = SITE + "/api/v1"
OUT = "knowledge/awesome-rea"
# The site rejects the default Python-urllib agent.
HEADERS = {"User-Agent": "rusphiltrade-knowledge-sync/1.0 (+https://rusphiltrade.com/)"}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=120) as r:
        return r.read()


def write(name, data):
    path = os.path.join(OUT, name)
    if isinstance(data, (dict, list)):
        data = json.dumps(data, ensure_ascii=False, indent=1) + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(data)


def one_line(s):
    return " ".join((s or "").split())


os.makedirs(OUT, exist_ok=True)

llms = get(SITE + "/llms.txt").decode("utf-8")
index = json.loads(get(API + "/index.json"))
files = {f["path"].rsplit("/", 1)[-1]: f for f in index["files"]}

api = {}
checksums = {}
for name in ("resources.json", "papers.json", "categories.json"):
    raw = get(API + "/" + name)
    digest = hashlib.sha256(raw).hexdigest()
    expected = files.get(name, {}).get("sha256")
    if expected and digest != expected:
        raise SystemExit(f"{name}: sha256 {digest} does not match index.json {expected}")
    api[name] = json.loads(raw)
    checksums[name] = {"url": API + "/" + name, "bytes": len(raw), "sha256": digest,
                       "verified_against_index": bool(expected)}

res_file, pap_file, cat_file = api["resources.json"], api["papers.json"], api["categories.json"]

resources = [{
    "id": r["id"],
    "name": r["name"],
    "url": r["url"],
    "entry_url": r["entry_url"],
    "category": r["category"],
    "kind": r["kind"],
    "relationship": r["relationship"],
    "targets": r.get("targets", []),
    "description": one_line(r.get("description_en")),
    "requirements": [one_line(x) for x in r.get("requirements", [])],
    "verified_at": r.get("verified_at"),
} for r in res_file["resources"]]

papers = [{
    "id": p["id"],
    "title": p["title"],
    "year": p.get("year"),
    "venue": p.get("venue"),
    "authors": p.get("authors", []),
    "url": p["url"],
    "code_url": p.get("code_url"),
    "entry_url": p["entry_url"],
    "targets": p.get("targets", []),
    "description": one_line(p.get("description_en")),
} for p in pap_file["papers"]]
papers.sort(key=lambda p: (-(p["year"] or 0), p["title"].lower()))

common = {"source": SITE + "/", "license": res_file["license"], "generated_at": res_file["generated_at"]}
write("llms.txt", llms)
write("categories.json", cat_file)
write("resources.json", {**common, "count": len(resources), "resources": resources})
write("papers.json", {**common, "count": len(papers), "papers": papers})

# INDEX.md: every curated resource under its category, papers by year.
labels = {c["id"]: c["label"] for c in cat_file["curated"]["categories"]}
by_cat = collections.defaultdict(list)
for r in resources:
    by_cat[r["category"]].append(r)
lines = [
    "# Awesome-REA: index of curated resources",
    "",
    f"Generated by `tools/sync_awesome_rea.py` from {API}/ "
    f"(catalog generated_at {res_file['generated_at']}). Do not edit by hand.",
    "",
    f"{len(resources)} resources, {len(papers)} papers. "
    "Each line: name, kind, targets, description. Full entry: the awesomerea.org link.",
    "",
    "## Categories",
    "",
]
order = [c["id"] for c in cat_file["curated"]["categories"] if c["id"] in by_cat]
order += sorted(set(by_cat) - set(order))
for cid in order:
    lines.append(f"- [{labels.get(cid, cid)}](#{cid}) ({len(by_cat[cid])})")
lines += ["- [Papers](#papers)", ""]
for cid in order:
    lines += [f'<a id="{cid}"></a>', f"## {labels.get(cid, cid)}", ""]
    for r in sorted(by_cat[cid], key=lambda r: r["name"].lower()):
        tags = r["kind"] + (" · " + ", ".join(r["targets"]) if r["targets"] else "")
        lines.append(f"- [{r['name']}]({r['url']}) — {tags} — {r['description']} ([entry]({r['entry_url']}))")
    lines.append("")
lines += ['<a id="papers"></a>', "## Papers", ""]
for p in papers:
    venue = ", ".join(str(x) for x in (p["venue"], p["year"]) if x)
    code = f" · [code]({p['code_url']})" if p["code_url"] else ""
    lines.append(f"- [{p['title']}]({p['url']}) ({venue}){code} — {p['description']}")
write("INDEX.md", "\n".join(lines) + "\n")

write("source.json", {
    "name": "Awesome Reverse Engineering Anything",
    "site": SITE + "/",
    "repository": "https://github.com/reacher-z/Awesome-REA",
    "llms_txt": SITE + "/llms.txt",
    "api": API + "/",
    "api_version": res_file["version"],
    "catalog_generated_at": res_file["generated_at"],
    "synced_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "license": res_file["license"],
    "counts": {
        "resources": len(resources),
        "papers": len(papers),
        "by_kind": dict(collections.Counter(r["kind"] for r in resources).most_common()),
        "by_target": dict(collections.Counter(t for r in resources for t in r["targets"]).most_common()),
    },
    "files": checksums,
})
print(len(resources), "resources,", len(papers), "papers, catalog", res_file["generated_at"])
